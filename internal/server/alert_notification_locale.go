package server

import (
	"fmt"
	"strconv"
)

func alertNotificationModule(module string) string {
	label := map[string]string{
		"files": "文件监控", "md5": "文件完整性", "existence": "文件存在性",
		"processes": "进程监控", "history": "操作命令", "login": "登录监控", "machine": "主机状态",
	}[module]
	if label != "" {
		return label + "（" + module + "）"
	}
	return module
}

func alertNotificationKind(kind string) string {
	label := map[string]string{
		"added": "新增", "modified": "修改", "deleted": "删除", "missing": "缺失",
		"not_found": "未找到", "missing_or_type_mismatch": "缺失或类型不符",
		"inspection_error": "检查异常", "collection_error": "采集异常", "parse_error": "解析异常",
	}[kind]
	if label != "" {
		return label + "（" + kind + "）"
	}
	return kind
}

// Translate only messages generated by known Agent versions. Custom messages
// and host diagnostics remain intact so notification evidence is not lost.
func alertNotificationMessage(module, kind, message, before, after string) string {
	switch module {
	case "md5":
		if message == "file content or membership changed" {
			return "文件内容或监控文件列表发生变化"
		}
	case "existence":
		if message == "configured file does not exist or has the wrong type" {
			return "配置的文件不存在或类型不符"
		}
	case "files":
		if translated := map[string]string{
			"configured file or directory does not exist":                  "配置的文件或目录不存在",
			"no regular file with the configured exact filename was found": "未找到与配置文件名完全匹配的普通文件",
			"monitored file added":                                         "监控文件已新增",
			"monitored file modified":                                      "监控文件已修改",
			"monitored file deleted":                                       "监控文件已删除",
		}[message]; translated != "" {
			return translated
		}
	case "processes":
		if message == "none of the required command alternatives is running" {
			return "配置要求的候选命令均未运行"
		}
		if kind == "added" || kind == "deleted" {
			previous, previousErr := strconv.Atoi(before)
			current, currentErr := strconv.Atoi(after)
			if previousErr == nil && currentErr == nil && previous >= 0 && current >= 0 && message == fmt.Sprintf("running instance count changed from %d to %d", previous, current) {
				return fmt.Sprintf("运行实例数量从 %d 变为 %d", previous, current)
			}
		}
	}
	return message
}
